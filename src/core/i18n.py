def month_name(month: int) -> str:
    names = _MONTHS.get(_current) or _MONTHS["en"]
    if 1 <= month <= 12:
        return names[month]
    return ""


def weekday_labels() -> list[str]:
    lang = _STRINGS.get(_current, _STRINGS["en"])
    return [lang.get(f"stats.weekday.{i}", _STRINGS["en"][f"stats.weekday.{i}"]) for i in range(7)]


def set_language(code: str) -> None:
    global _current
    if code in _STRINGS:
        _current = code


def get_language() -> str:
    return _current


def tr(key: str, **kwargs) -> str:
    text = _STRINGS.get(_current, _STRINGS["en"]).get(
        key, _STRINGS["en"].get(key, key)
    )
    if kwargs:
        return text.format(**kwargs)
    return text


def _merge_partial_locales() -> None:
    english = _STRINGS["en"]
    for code in ("de", "fr", "es", "pl"):
        merged = dict(english)
        merged.update(_STRINGS.get(code, {}))
        _STRINGS[code] = merged


